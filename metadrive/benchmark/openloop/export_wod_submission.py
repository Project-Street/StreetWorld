import argparse
import json
import math
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(
        description="Convert JSON predictions into Waymo E2E submission shards."
    )
    parser.add_argument(
        "--input_json",
        required=True,
        help="Path to JSON predictions generated by predict_wod_last_uniad.py",
    )
    parser.add_argument(
        "--output_dir",
        required=True,
        help="Output directory for Waymo submission shards",
    )
    parser.add_argument(
        "--submission_name",
        default="MySubmission",
        help="Directory name under output_dir for submission shards",
    )
    parser.add_argument(
        "--num_shards",
        type=int,
        default=1,
        help="Number of submission shards to write",
    )
    args = parser.parse_args()

    try:
        from waymo_open_dataset.protos import end_to_end_driving_submission_pb2
    except ImportError as exc:
        raise ImportError(
            "Missing waymo_open_dataset package. Install the Waymo Open Dataset Python "
            "package to access end_to_end_driving_submission_pb2."
        ) from exc

    input_path = Path(args.input_json)
    with input_path.open("r", encoding="utf-8") as fp:
        payload = json.load(fp)

    predictions = payload.get("predictions", [])
    if not predictions:
        raise ValueError(f"No predictions found in {input_path}")

    if args.num_shards < 1:
        raise ValueError("num_shards must be >= 1")

    output_root = Path(args.output_dir) / args.submission_name
    output_root.mkdir(parents=True, exist_ok=True)

    num_predictions_per_shard = int(math.ceil(len(predictions) / args.num_shards))
    for shard_idx in range(args.num_shards):
        start = shard_idx * num_predictions_per_shard
        end = min((shard_idx + 1) * num_predictions_per_shard, len(predictions))
        if start >= end:
            break

        shard_predictions = []
        for item in predictions[start:end]:
            frame_name = item["frame_name"]
            pos_x = item["pos_x"]
            pos_y = item["pos_y"]
            trajectory = end_to_end_driving_submission_pb2.TrajectoryPrediction(
                pos_x=pos_x,
                pos_y=pos_y,
            )
            frame_prediction = end_to_end_driving_submission_pb2.FrameTrajectoryPredictions(
                frame_name=frame_name,
                trajectory=trajectory,
            )
            shard_predictions.append(frame_prediction)

        submission = end_to_end_driving_submission_pb2.E2EDChallengeSubmission(
            predictions=shard_predictions
        )
        submission.authors[:] = ['jrguo']  # Please modify accordingly.
        submission.affiliation = 'Zhejiang University'  # Please modify accordingly.
        submission.account_name = 'jrguo888@gmail.com'  # Please modify accordingly.
        submission.unique_method_name = 'UniAD-RL'  # Please modify accordingly.
        submission.method_link = 'none'  # Please modify accordingly.
        submission.description = ''  # Please modify accordingly.
        submission.uses_public_model_pretraining = True # Please modify accordingly.
        submission.public_model_names.extend(['uniad']) # Please modify accordingly.
        submission.num_model_parameters = "200k" # Please modify accordingly.
        shard_path = output_root / f"mysubmission.binproto-{shard_idx:05d}-of-{args.num_shards:05d}"
        with shard_path.open("wb") as fp:
            fp.write(submission.SerializeToString())
        print(f"Wrote shard {shard_path} ({end - start} predictions)")


if __name__ == "__main__":
    main()
